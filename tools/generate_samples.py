"""Create deterministic, explicitly synthetic teaching fixtures."""

from pathlib import Path
import csv
import hashlib
import io
import json
import random

ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / "public" / "samples"
DESTINATION.mkdir(parents=True, exist_ok=True)

random_source = random.Random(20261117)
headers = ["样本编号", "时间_s", "参考压力_kPa", "传感器输出_mV", "温度_℃", "实验组"]
rows = []
for index in range(160):
    pressure = 5 + (index % 80) * 1.2
    voltage = 8.7 + 1.876 * pressure + random_source.gauss(0, 0.7)
    rows.append([
        f"{index + 1:03d}",
        str(index * 10),
        f"{pressure:.2f}",
        f"{voltage:.3f}",
        f"{24 + random_source.gauss(0, 0.25):.2f}",
        "A 组" if index < 80 else "B 组",
    ])

for index, column in [(12, 3), (47, 3), (91, 4), (123, 4)]:
    rows[index][column] = ""
for index, column, value in [(31, 3, "ERR"), (87, 3, "等待校准"), (114, 4, "25℃")]:
    rows[index][column] = value
for index, column, value in [(18, 3, "580.000"), (105, 3, "-120.000"), (139, 4, "72.00")]:
    rows[index][column] = value
rows[8][5] = " A 组 "
rows[59][5] = "B 组  "
for duplicate in [5, 76, 150]:
    rows.append(rows[duplicate].copy())

stream = io.StringIO(newline="")
writer = csv.writer(stream)
writer.writerow(headers)
writer.writerows(rows)
data = stream.getvalue().encode("utf-8-sig")
(DESTINATION / "sensor-calibration.csv").write_bytes(data)

try:
    from openpyxl import Workbook

    book = Workbook()
    sheet = book.active
    sheet.title = "传感器标定"
    sheet.append(headers)
    for row in rows:
        sheet.append(row)
    second = book.create_sheet("边界案例")
    second.append(["样本编号", "日期", "读数", "备注"])
    for record in [
        ["001", "2024-02-29", "1,234.5", '包含引号 "示例"'],
        ["002", "2026-02-30", "12mg", "无效日期与带单位数值"],
        ["003", "2026-11-18", "", "缺失值"],
        ["004", "2026-11-18", "1235", "普通值"],
        ["005", "2026-11-18", "1236", "普通值"],
        ["006", "2026-11-18", "1237", "普通值"],
    ]:
        second.append(record)
    book.save(DESTINATION / "sensor-calibration.xlsx")
except ImportError:
    pass

manifest = {
    "source": "Synthetic teaching fixture generated by tools/generate_samples.py",
    "seed": 20261117,
    "rows": len(rows),
    "columns": len(headers),
    "injected_missing_cells": 4,
    "injected_invalid_numeric_cells": 3,
    "extra_duplicate_rows": 3,
    "injected_extreme_values": 3,
    "injected_whitespace_cells": 2,
    "base_relation": "sensor_mV = 8.7 + 1.876 * pressure_kPa + Normal(0, 0.7)",
    "csv_sha256": hashlib.sha256(data).hexdigest(),
    "note": "IQR flags are recomputed from imported observations and can include natural simulated tails.",
}
(DESTINATION / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
print(json.dumps(manifest, ensure_ascii=False))
